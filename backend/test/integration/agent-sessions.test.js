import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import pg from 'pg';
import {migrate} from '../../src/research/migrate.js';
import {createAgentSessionStore} from '../../src/research/agent-sessions.js';
import {createAgentPolicy} from '../../src/research/agent-policy.js';
import {createArtifactStore} from '../../src/research/artifacts.js';
import {scenarioServices,textualScenario} from '../../test-support/research-scenario.js';
const url=process.env.TEST_DATABASE_URL;
if(url && !new URL(url).pathname.startsWith('/tcc_test_'))throw new Error('Use banco tcc_test_.');
test('sessões preservam referências, orçamento, idempotência e posse concorrente',{skip:!url},async()=>{
  const pool=new pg.Pool({connectionString:url}),dir=await mkdtemp(join(tmpdir(),'agent-session-'));
  const store=createArtifactStore(dir);
  try {
    await migrate(pool);assert.deepEqual(await migrate(pool),[]);
    const services=scenarioServices(pool,store),{run,inspection}=await textualScenario(services);
    const {createAutomationService}=await import('../../src/research/automation.js');
    await createAutomationService({pool,store}).start(run.id,{inspection_id:inspection.inspection_id,module_root:'',justification:'Fixture AG-02.'});
    const stage=(await pool.query("SELECT * FROM research.stages WHERE run_id=$1 AND agent='automation'",[run.id])).rows[0];
    const part=(await pool.query('SELECT * FROM research.automation_parts WHERE run_id=$1 LIMIT 1',[run.id])).rows[0];
    const token=randomUUID(),attemptId=randomUUID();
    await pool.query("UPDATE research.stages SET status='running',lease_token=$2,lease_until=now()+interval '3 minutes' WHERE id=$1",[stage.id,token]);
    await pool.query("INSERT INTO research.attempts(id,stage_id,number,status,automation_part_id) VALUES($1,$2,1,'running',$3)",[attemptId,stage.id,part.id]);
    const job={run,stage,token,attemptId,automationPart:part},sessions=createAgentSessionStore(pool,job);
    const policy=createAgentPolicy({modes:{automation:'agent/v1'},limits:{max_model_turns:1}});
    const context=await store.put({fixture:true}),session=await sessions.create({task:{case_ids:[]},policy,context});
    assert.equal((await sessions.create({task:{},policy,context})).id,session.id);
    const requested=await Promise.allSettled([sessions.beginStep(session.id,context),sessions.beginStep(session.id,context)]);
    assert.equal(requested.filter(r=>r.status==='fulfilled').length,1);
    const step=requested.find(r=>r.status==='fulfilled').value;
    await sessions.completeStep(session.id,step.id,context,{usage:{totalTokenCount:10}});
    await sessions.completeStep(session.id,step.id,context,{usage:{totalTokenCount:10}});
    assert.equal(Number((await sessions.get(session.id)).total_tokens),10);
    await assert.rejects(sessions.beginStep(session.id,context),/Orçamento/);
    const call={id:'call-1',name:'list_sources'},first=await sessions.beginCall(session.id,step.id,call,context);
    assert.equal((await sessions.beginCall(session.id,step.id,call,context)).id,first.id);
    await sessions.completeCall(session.id,first.id,context);await sessions.completeCall(session.id,first.id,context);
    assert.equal((await sessions.get(session.id)).tool_calls,1);
    const foreignJob={...job,token:randomUUID()};
    await assert.rejects(createAgentSessionStore(pool,foreignJob).finish(session.id,'completed','forged'),/Posse/);
    await assert.rejects(pool.query('UPDATE research.agent_sessions SET project_id=$2 WHERE id=$1',[session.id,randomUUID()]),{code:'23503'});
    await assert.rejects(pool.query('INSERT INTO research.agent_tool_calls(id,session_id,step_id,call_id,name,tool_version,arguments,status) VALUES($1,$2,$3,$4,$5,$6,$7,$8)',[randomUUID(),randomUUID(),step.id,'other','read_source','1',context,'requested']),{code:'23503'});
    await sessions.finish(session.id,'exhausted','turn_limit');
    await assert.rejects(sessions.beginStep(session.id,context),/encerrada/);
    assert.equal((await sessions.get(session.id)).status,'exhausted');
    const nextAttempt=randomUUID();
    await pool.query("INSERT INTO research.attempts(id,stage_id,number,status,automation_part_id) VALUES($1,$2,2,'running',$3)",[nextAttempt,stage.id,part.id]);
    const nextStore=createAgentSessionStore(pool,{...job,attemptId:nextAttempt});
    const next=await nextStore.create({task:{case_ids:[]},policy,context});
    await assert.rejects(nextStore.beginStep(next.id,context),/Orçamento/);
    await nextStore.finish(next.id,'exhausted','inherited_turn_limit');
  } finally{await pool.end();await rm(dir,{recursive:true,force:true});}
});
