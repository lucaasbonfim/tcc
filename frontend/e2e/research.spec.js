import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('pesquisador cadastra projeto, importa documento, revisa agentes e exporta histórico', async ({page},testInfo) => {
  const errors = [];
  page.on('pageerror',error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Acesso do pesquisador'})).toBeVisible({timeout:20000});
  await page.getByLabel('E-mail',{exact:true}).fill('researcher@example.test');
  await page.getByLabel('Senha',{exact:true}).fill('E2E-Research-Only');
  await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Da especificação à evidência.'})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('dashboard-desktop.png'),fullPage:true});
  await page.getByRole('link',{name:'+ Cadastrar projeto',exact:true}).click();
  const name = `Projeto E2E ${Date.now()}`;
  await page.getByLabel('Nome do projeto',{exact:true}).fill(name);
  await page.getByLabel('Repositório público do GitHub').fill('https://github.com/example/repo');
  await page.getByRole('button',{name:'Salvar projeto e registrar SHA'}).click();
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
  await page.getByLabel('Selecionar documento').setInputFiles({name:'requisitos.txt',mimeType:'text/plain',buffer:Buffer.from('O sistema deve permitir consultar projetos.')});
  await page.getByRole('button',{name:'Adicionar documento',exact:true}).click();
  await expect(page.getByText('requisitos.txt · v1 · 1 páginas')).toBeVisible();
  await page.getByRole('button',{name:'Consultar extração'}).click();
  await expect(page.getByRole('heading',{name:'requisitos.txt · v1'})).toBeVisible();
  await page.getByRole('button',{name:'Iniciar análise de requisitos'}).click();
  await expect(page.getByRole('heading',{name:'Consulta de projetos',exact:true})).toBeVisible({timeout:20000});
  await page.getByRole('button',{name:'Corrigir conteúdo'}).click();
  await page.getByRole('textbox',{name:'Título',exact:true}).fill('Consulta de projetos revisada');
  await expect(page.getByRole('button',{name:'Aprovar todos e gerar casos de teste'})).toBeDisabled();
  await page.getByRole('button',{name:'Salvar correção',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Consulta de projetos revisada',exact:true})).toBeVisible();
  await expect(page.locator('.review-item .status-pending')).toBeVisible();
  await page.getByRole('button',{name:'Aprovar todos e gerar casos de teste'}).click();
  await expect(page.getByRole('heading',{name:'Consultar projetos cadastrados',exact:true})).toBeVisible({timeout:20000});
  await page.getByRole('button',{name:'Aprovar todos e continuar'}).click();
  await expect(page.locator('.heading-actions .status-completed')).toBeVisible();
  await page.getByRole('button',{name:'Scripts',exact:true}).click();
  await page.getByRole('button',{name:'Inspecionar fontes deste commit'}).click();
  await page.getByLabel('src/projects.js',{exact:true}).check();
  await page.getByRole('textbox',{name:'Justificativa do escopo e da geração'}).fill('Escopo de fonte conhecido da fixture.');
  await page.getByRole('button',{name:'Gerar scripts dos casos aprovados'}).click();
  await expect(page.getByRole('heading',{name:'Script node-test/v2 · versão 1'})).toBeVisible({timeout:20000});
  await page.getByRole('textbox',{name:'Justificativa da revisão do script'}).fill('Import, asserções e esperado conferidos na fixture.');
  await page.getByRole('button',{name:'Aprovar script',exact:true}).click();
  await expect(page.locator('.review-item .status-approved')).toBeVisible();
  await page.getByRole('textbox',{name:'Justificativa da aprovação dos scripts'}).fill('Revisão dos scripts concluída na fixture.');
  await page.getByRole('button',{name:'Concluir revisão dos scripts'}).click();
  await page.getByRole('button',{name:'Execução',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Execução de testes não suportada'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Autorizar execução isolada'})).toBeDisabled();
  await page.request.post('http://localhost:3101/__e2e/enable-executor');
  await page.getByRole('button',{name:'Verificar executor'}).click();
  await page.getByRole('textbox',{name:'Justificativa da autorização de execução'}).fill('Somente integração E2E, não execução de código.');
  await expect(page.getByRole('button',{name:'Autorizar execução isolada'})).toBeEnabled();
  await page.getByRole('button',{name:'Autorizar execução isolada'}).click();
  await expect(page.getByText('Fixture: assert sem falha.',{exact:true})).toBeVisible({timeout:20000});
  await page.getByRole('button',{name:'Análise',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Comportamento compatível no cenário'})).toBeVisible({timeout:20000});
  await page.getByRole('textbox',{name:'Justificativa da decisão humana'}).fill('Evidência sintética conferida no teste da interface.');
  await page.getByRole('button',{name:'Confirmar classificação'}).click();
  await expect(page.locator('.review-item .status-confirmed')).toBeVisible();
  await page.getByRole('textbox',{name:'Justificativa da conclusão da avaliação'}).fill('Fluxo E2E concluído; sem dados experimentais.');
  await page.getByRole('button',{name:'Concluir revisão da avaliação'}).click();
  await expect(page.locator('.heading-actions .status-completed')).toBeVisible();
  await page.getByRole('button',{name:'Histórico e configuração'}).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button',{name:'Exportar JSON'}).click();
  const file = await download;
  expect(file.suggestedFilename()).toMatch(/^research-.*\.json$/);
  const exported = JSON.parse(await readFile(await file.path(),'utf8'));
  expect(exported.requirements[0].content.title).toBe('Consulta de projetos revisada');
  expect(exported.traceability).toHaveLength(1);
  expect(exported.stages[2].status).toBe('completed');
  expect(exported.automated_tests).toHaveLength(1);
  expect(exported.evidence).toHaveLength(1);
  expect(exported.findings[0].review_status).toBe('confirmed');
  expect(exported.attempts[0].output_data.raw).toContain('Consulta de projetos');
  expect(exported.reviews[0].before_value.content.title).toBe('Consulta de projetos');
  expect(exported.reviews[0].decision).toBe('edited');
  expect(exported.reviews.filter(review=>review.entity_type==='stage' && review.after_value?.approval_mode==='bulk')).toHaveLength(2);
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('navigation',{name:'Navegação principal'})).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({path:testInfo.outputPath('historico-mobile.png'),fullPage:true});
  expect(errors).toEqual([]);
});
